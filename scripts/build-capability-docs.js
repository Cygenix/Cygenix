#!/usr/bin/env node
/* ============================================================================
   build-capability-docs.js — writes the supported-matrix section of the help
   site from public/cygenix-capabilities.js.
   ----------------------------------------------------------------------------
   The help page said Cygenix connects "to your source and target SQL Server
   databases" while the product had a full PostgreSQL driver and the pricing
   page sold Postgres from the Pro tier. Nobody wrote that inconsistency on
   purpose; the page was simply written once and the product moved.

   Hand-editing it again would buy a few months. Generating it means the page
   cannot say something the manifest does not, because nobody types the page.

   The generated block is delimited by markers in help.html:

       <!-- CAPABILITY-MATRIX:START -->  … generated …  <!-- CAPABILITY-MATRIX:END -->

   Everything outside them is hand-written and untouched.

   Run: node scripts/build-capability-docs.js
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const CAP = require('../public/cygenix-capabilities.js');

const HELP = path.join(__dirname, '..', 'public', 'help.html');
const START = '<!-- CAPABILITY-MATRIX:START -->';
const END   = '<!-- CAPABILITY-MATRIX:END -->';

const esc = (s) => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* A status becomes a coloured chip. `planned` and `unsupported` are stated
   plainly rather than omitted — a matrix that lists only what works is a
   marketing table, not documentation. */
const CHIP_COLOUR = {
  ga:          ['var(--green)',  'rgba(34,201,122,0.12)'],
  beta:        ['var(--accent)', 'rgba(74,91,214,0.12)'],
  preview:     ['var(--amber)',  'rgba(245,158,11,0.12)'],
  planned:     ['var(--text3)',  'transparent'],
  unsupported: ['var(--red)',    'rgba(240,70,70,0.10)'],
};
function chip(status) {
  const [fg, bg] = CHIP_COLOUR[status] || CHIP_COLOUR.planned;
  return '<span style="display:inline-block;font-size:10.5px;font-weight:500;padding:1px 7px;'
    + 'border-radius:100px;color:' + fg + ';background:' + bg + ';white-space:nowrap">'
    + esc(CAP.STATUS_LABEL[status] || status) + '</span>';
}

const VERDICT_TEXT = {
  supported:              ['Moves as-is',        'var(--green)'],
  supported_with_changes: ['Moves, with changes', 'var(--accent)'],
  requires_equivalent:    ['Needs an equivalent', 'var(--amber)'],
  unsupported:            ['Not possible',        'var(--red)'],
  not_applicable:         ['—',                   'var(--text3)'],
};
function verdict(v) {
  const [text, colour] = VERDICT_TEXT[v] || ['—', 'var(--text3)'];
  return '<span style="color:' + colour + ';font-size:11.5px">' + esc(text) + '</span>';
}

function render() {
  const L = [];
  L.push(START);
  L.push('<!-- GENERATED by scripts/build-capability-docs.js from');
  L.push('     public/cygenix-capabilities.js. Do not edit inside these markers:');
  L.push('     the next run overwrites it, and tests/capabilities.test.js fails');
  L.push('     while the page and the manifest disagree. -->');

  L.push('      <h2>What Cygenix supports</h2>');
  L.push('      <p>This table is generated from the product\'s capability manifest, so it is what the '
       + 'software actually does rather than what it was described as doing when this page was last '
       + 'written by hand.</p>');

  /* ── Sources ─────────────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-sources">Sources</h3>');
  L.push('      <table><thead><tr><th>Source</th><th>Status</th><th>Notes</th></tr></thead><tbody>');
  for (const s of CAP.SOURCES) {
    L.push('        <tr><td><strong>' + esc(s.label) + '</strong>'
      + (s.versions ? ' <span style="color:var(--text3);font-size:11px">' + esc(s.versions) + '</span>' : '')
      + '</td><td>' + chip(s.status) + '</td><td>' + esc(s.detail || '') + '</td></tr>');
  }
  L.push('      </tbody></table>');

  /* ── Targets ─────────────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-targets">Targets</h3>');
  L.push('      <table><thead><tr><th>Target</th><th>Status</th><th>Notes</th></tr></thead><tbody>');
  for (const t of CAP.TARGETS) {
    L.push('        <tr><td><strong>' + esc(t.label) + '</strong>'
      + (t.versions ? ' <span style="color:var(--text3);font-size:11px">' + esc(t.versions) + '</span>' : '')
      + '</td><td>' + chip(t.status) + '</td><td>' + esc(t.detail || '') + '</td></tr>');
  }
  L.push('      </tbody></table>');

  /* ── Pairs ───────────────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-pairs">Source and target combinations</h3>');
  L.push('      <p>A combination absent from this table has not been assessed. Cygenix refuses it '
       + 'rather than assuming it works.</p>');
  L.push('      <table><thead><tr><th>From</th><th>To</th><th>Status</th><th>Server-level objects</th>'
       + '</tr></thead><tbody>');
  for (const p of CAP.PAIRS) {
    const s = CAP.source(p.source), t = CAP.target(p.target);
    L.push('        <tr><td>' + esc(s ? s.label : p.source) + '</td><td>' + esc(t ? t.label : p.target)
      + '</td><td>' + chip(p.status) + '</td><td>' + verdict(p.serverObjects) + '</td></tr>');
  }
  L.push('      </tbody></table>');

  /* ── Server objects ──────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-server-objects">Server-level objects, by target</h3>');
  L.push('      <p>Logins, Agent jobs, SSIS projects and linked servers live at the server level, and '
       + 'target platforms differ enormously in what they can accept. Cygenix assesses this '
       + '<em>before</em> a run and says what it will and will not move, rather than failing partway '
       + 'through. Where a target cannot take an object, the equivalent construct is named.</p>');
  const soTargets = ['mssql', 'azuresqlmi', 'azuresqldb', 'postgres'];
  L.push('      <table><thead><tr><th>Object</th>'
    + soTargets.map(id => '<th>' + esc((CAP.target(id) || {}).label || id) + '</th>').join('')
    + '</tr></thead><tbody>');
  for (const o of CAP.SERVER_OBJECTS) {
    const cells = soTargets.map(id => {
      const s = CAP.serverObjectSupport(o.id, id);
      const note = s.equivalent ? '<div style="color:var(--text3);font-size:10.5px;margin-top:2px">'
        + esc(s.equivalent) + '</div>' : '';
      return '<td>' + verdict(s.verdict) + note + '</td>';
    }).join('');
    L.push('        <tr><td><strong>' + esc(o.label) + '</strong></td>' + cells + '</tr>');
  }
  L.push('      </tbody></table>');

  /* ── Features ────────────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-features">Features</h3>');
  L.push('      <table><thead><tr><th>Feature</th><th>Status</th><th>From plan</th><th>Notes</th>'
       + '</tr></thead><tbody>');
  for (const f of CAP.FEATURES) {
    const t = CAP.tier(f.minTier);
    L.push('        <tr><td><strong>' + esc(f.label) + '</strong></td><td>' + chip(f.status)
      + '</td><td>' + esc(t ? t.label : (f.minTier || '—')) + '</td><td>'
      + esc(f.detail || '') + '</td></tr>');
  }
  L.push('      </tbody></table>');

  /* ── Limits ──────────────────────────────────────────────────────────── */
  L.push('      <h3 id="supported-limits">Plan limits</h3>');
  L.push('      <p>Enforced server-side when a job is admitted. Exceeding one names the limit and '
       + 'the plan rather than failing generically.</p>');
  L.push('      <table><thead><tr><th>Limit</th>'
    + CAP.TIERS.map(t => '<th>' + esc(t.label) + '</th>').join('') + '</tr></thead><tbody>');
  const num = (v) => v == null ? 'Unlimited' : v.toLocaleString();
  const rows = [
    ['Concurrent migrations', 'concurrentMigrations'],
    ['Max rows per job',      'maxRowsPerJob'],
    ['Job submissions a month', 'monthlySubmissions'],
    ['History retention (days)', 'retentionDays'],
  ];
  for (const [label, key] of rows) {
    L.push('        <tr><td>' + esc(label) + '</td>'
      + CAP.TIERS.map(t => '<td>' + esc(num(t[key])) + '</td>').join('') + '</tr>');
  }
  L.push('      </tbody></table>');

  L.push(END);
  return L.join('\n');
}

function apply() {
  let html = fs.readFileSync(HELP, 'utf8');
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a === -1 || b === -1) {
    throw new Error('help.html is missing the CAPABILITY-MATRIX markers — '
      + 'add ' + START + ' and ' + END + ' where the section should go.');
  }
  const next = html.slice(0, a) + render() + html.slice(b + END.length);
  const changed = next !== html;
  if (changed) fs.writeFileSync(HELP, next);
  return changed;
}

if (require.main === module) {
  const changed = apply();
  console.log('build-capability-docs: ' + (changed ? 'updated' : 'already current')
    + ' — ' + CAP.SOURCES.length + ' source(s), ' + CAP.TARGETS.length + ' target(s), '
    + CAP.PAIRS.length + ' pair(s), ' + CAP.FEATURES.length + ' feature(s)');
}

module.exports = { render, apply, START, END };
